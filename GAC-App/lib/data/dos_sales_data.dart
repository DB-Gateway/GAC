/// Builds the canonical Sales checklist while retaining server item IDs and
/// keys when an API template already contains the corresponding row number.
ChecklistTemplateData buildDosSalesTemplateData({
  ChecklistTemplateData? source,
}) {
  final remoteItemsByNumber = <int, ChecklistItemData>{};
  if (source != null) {
    for (final item in source.sections.expand((section) => section.items)) {
      final number =
          int.tryParse(item.displayNumber ?? '') ??
          int.tryParse(item.key.replaceAll(RegExp(r'[^0-9]'), ''));
      if (number != null) remoteItemsByNumber[number] = item;
    }
  }

  final sections = dosTemplate.indexed
      .map((entry) {
        final (sectionIndex, section) = entry;
        return ChecklistSectionData(
          id: 0,
          key: section.id,
          title: section.title,
          sortOrder: sectionIndex,
          metadata: const {},
          items: section.items
              .map((item) {
                final itemNumber =
                    int.tryParse(item.id.replaceAll(RegExp(r'[^0-9]'), '')) ??
                    0;
                final remoteItem = remoteItemsByNumber[itemNumber];
                return ChecklistItemData(
                  id: remoteItem?.id ?? itemNumber,
                  key: remoteItem?.key ?? item.id,
                  prompt: item.text,
                  sortOrder: itemNumber,
                  description: remoteItem?.description,
                  metadata: {
                    ...?remoteItem?.metadata,
                    'number': itemNumber,
                    'level': item.level,
                    'category': item.level,
                    'coverage': item.coverage,
                    'subject': item.subject,
                    'checker': item.checker,
                    'pic': 'GM',
                    'bom_task': item.bomTask,
                    'escalation': item.escalation,
                    'how_to_check': item.howToCheck,
                  },
                );
              })
              .toList(growable: false),
        );
      })
      .toList(growable: false);

  return ChecklistTemplateData(
    id: source?.id ?? 6,
    slug: source?.slug ?? 'dealer-operations-standards-sales',
    name: source?.name ?? 'Dealer Operations Standards - Sales',
    description:
        'FY25 Sales Standards Compliance Audit Sheet (REV02) (90 Standards)',
    version: source?.version ?? 1,
    settings:
        source?.settings ??
        const {
          'validation_mode': 'dos',
          'response_options': ['yes', 'no', 'na'],
          'instructions': 'Judge every standard. NO requires a finding and action plan; N/A requires a reason.',
        },
    sections: sections,
  );
}
