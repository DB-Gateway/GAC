ChecklistTemplateData buildSubformTemplateData() {
  final sections = dosSubformTemplate
      .map((sec) {
        return ChecklistSectionData(
          id: 0,
          key: sec.id,
          title: sec.title,
          sortOrder: 0,
          metadata: const {'prerequisite_cascade': true},
          items: sec.items
              .map((item) {
                final itemNumber =
                    int.tryParse(item.id.replaceAll(RegExp(r'[^0-9]'), '')) ??
                    0;
                return ChecklistItemData(
                  id: itemNumber,
                  key: item.id,
                  prompt: item.text,
                  sortOrder: itemNumber,
                  metadata: {
                    'number': itemNumber,
                    'level': item.level,
                    'category': item.level,
                    'coverage': item.coverage,
                    'subject': item.subject,
                    'checker': item.checker,
                    'pic': 'GM',
                    'bom_task': item.bomTask,
                    'escalation': item.escalation,
                    'how_to_check': item.howToCheck,
                    'prerequisite_cascade': true,
                  },
                );
              })
              .toList(growable: false),
        );
      })
      .toList(growable: false);

  return ChecklistTemplateData(
    id: 10,
    slug: 'dealer-operations-standards-subform',
    name: 'Dealer Operations Standards - Subform',
    description: 'FY2025 Aftersales Standards Compliance Audit Subform (39 Standards). If any standard is No, prerequisite standards in that section cascade to No.',
    version: 1,
    settings: const {
      'validation_mode': 'dos_subform',
      'response_options': ['yes', 'no', 'na'],
      'instructions': 'Check each standard according to your assigned role. Note: Choosing "No" triggers a prerequisite cascade setting related items in the section to No.',
      'prerequisite_cascade': true,
    },
    sections: sections,
  );
}
